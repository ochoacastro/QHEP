const C={k:'kA',uid:'uA',wa:'3155555233',ts:serverTimestamp()};
await t('Dueña crea su código',true,()=>setDoc(doc(U,'celcod/482913'),C));
await t('Nadie lee el código (ni la dueña)',false,()=>getDoc(doc(U,'celcod/482913')));
await t('Otro no reusa el mismo código',false,()=>setDoc(doc(O,'celcod/482913'),{...C,uid:'uO'}));
await t('Otro no crea código para el plan ajeno',false,()=>setDoc(doc(O,'celcod/111111'),{...C,uid:'uO'}));
await t('No con uid ajeno',false,()=>setDoc(doc(O,'celcod/222222'),C));
await t('Código que no es de 6 números',false,()=>setDoc(doc(U,'celcod/abc'),C));
await t('Celular no válido',false,()=>setDoc(doc(U,'celcod/333333'),{...C,wa:'123'}));
await t('Campo extra',false,()=>setDoc(doc(U,'celcod/444444'),{...C,x:1}));
await t('Hora del celular (no del servidor)',false,()=>setDoc(doc(U,'celcod/555555'),{...C,ts:Date.now()}));
