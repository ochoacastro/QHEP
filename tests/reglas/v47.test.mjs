import {initializeTestEnvironment} from '@firebase/rules-unit-testing';
import {doc,setDoc,updateDoc,getDoc,deleteDoc,serverTimestamp} from 'firebase/firestore';import fs from 'fs';
const env=await initializeTestEnvironment({projectId:'demo-qhep47',firestore:{rules:fs.readFileSync(process.env.RULES,'utf8'),host:'127.0.0.1',port:8089}});
await env.clearFirestore();const now=Date.now();
const real=(uid,email,v=true)=>env.authenticatedContext(uid,{email,email_verified:v,firebase:{sign_in_provider:'password'}}).firestore();
const U=real('uA','a@x.co'),O=real('uO','o@x.co'),NV=real('uA','a@x.co',false);
await env.withSecurityRulesDisabled(async c=>{await setDoc(doc(c.firestore(),'plans/kA'),{k:'kA',name:'Ana',email:'a@x.co',uid:'uA',plan:'free',trial:false,paid:false,featSlots:0,start:now,end:now+9e9})});
